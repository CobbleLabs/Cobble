"""Turn a CbMapper TSV into the C++ mapping table Cobble links in.

Only classes Cobble names (plus their superclasses) and members whose MCP or SRG name appears as a
string literal in src/ are emitted, so the table grows with the code that needs it.

usage: python -I gen_header.py <cobble/src> <mapping.tsv> <out.hpp> <TableName> <MinecraftVersion enumerator>
"""
import re
import sys
from pathlib import Path

LOOKUP = re.compile(r'(?:Get(?:Static)?(?:Field|Method)ID|TRY_(?:STATIC_)?(?:FIELD|METHOD))\s*\((.*?)\)\s*[;)]', re.S)
LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')
DESCRIPTOR = re.compile(r'^(\(.*\).+|\[*[BCDFIJSZ]|\[*L[^;]+;)$')


def main(src, tsv, out, table, version):
    classes, supers, members = {}, {}, []
    for line in tsv.read_text(encoding="utf-8").splitlines():
        row = line.split("\t")
        if row[0] == "CL":
            classes[row[1]] = row[3]
            supers[row[1]] = row[4]
        else:
            members.append(row)

    literals, referenced, lookups = set(), set(), set()
    for path in sorted(src.rglob("*")):
        if path.suffix not in (".cpp", ".h", ".hpp") or path == out:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        literals.update(LITERAL.findall(text))
        referenced.update(c.replace(".", "/") for c in re.findall(r'"(net[./]minecraft[./][\w./$]+)"', text))
        referenced.update(re.findall(r'L(net/minecraft/[\w/$]+);', text))
        for call in LOOKUP.finditer(text):
            args = LITERAL.findall(call.group(1))
            if len(args) >= 2 and DESCRIPTOR.match(args[1]):
                lookups.add((args[0], args[1]))

    owners = set()
    for name in referenced:
        while name in classes and name not in owners:
            owners.add(name)
            name = supers[name]

    selected = sorted({(r[1], r[2], r[3], r[4], r[6], r[7]) for r in members
                       if r[1] in owners and (r[2] in literals or r[3] in literals) and r[6] != r[2]})
    emitted = set(owners)
    for _, _, _, desc, _, _ in selected:
        emitted.update(c for c in re.findall(r"L([^;]+);", desc) if c in classes)

    lines = [
        f"// Generated by tools/cbmap/gen_header.py from {tsv.name}. Regenerate instead of editing.",
        "#pragma once",
        "",
        '#include "runtime_mappings.hpp"',
        "",
        "namespace mappings {",
        "",
        f"inline constexpr ClassMapping {table}Classes[] = {{",
    ]
    lines += [f'    {{"{c}", "{classes[c]}"}},' for c in sorted(emitted)]
    lines += ["};", "", f"inline constexpr MemberMapping {table}Members[] = {{"]
    lines += [f'    {{"{o}", "{m}", "{s}", "{d}", "{n}", "{rd}"}},' for o, m, s, d, n, rd in selected]
    lines += [
        "};",
        "",
        f"inline constexpr RuntimeMappings {table}{{MinecraftVersion::{version}, {table}Classes, {table}Members}};",
        "",
        "}  // namespace mappings",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    known = {(r[2], r[4]) for r in members} | {(r[3], r[4]) for r in members}
    unresolved = sorted(k for k in lookups if k not in known and ("net/minecraft" in k[1] or k[0].startswith(("field_", "func_"))))
    print(f"{len(emitted)} classes, {len(selected)} members -> {out}")
    print(f"referenced classes without mapping: {sorted(c for c in referenced if c not in classes)}")
    print(f"MC-typed lookups without mapping (other versions or other names): {len(unresolved)}")
    for name, desc in unresolved:
        print(f"  {name} {desc}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), sys.argv[4], sys.argv[5])
