# generate_config.ps1
# Reads cobble.json and generates obfuscated C++ headers.
# All secrets are compile-time encrypted — nothing appears in plaintext in the binary.
# Run automatically by build.ps1 before compilation.

param([string]$ConfigPath = "$PSScriptRoot\cobble.json")

$ErrorActionPreference = "Stop"
$config = Get-Content $ConfigPath -Raw | ConvertFrom-Json

$host_ = $config.server.host
$port = $config.server.port
$https = $config.server.https
$version = $config.version
$pubKeyHex = $config.public_key_hex
$payloadKey = $config.payload_key

# ============================================================================
# Security: Generate random XOR masks per build (changes every compile)
# This means even if a reverser finds the key in one build, the offsets/masks
# are different in the next build. Polymorphic at compile time.
# ============================================================================
$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()

function Get-RandomByte {
    $buf = [byte[]]::new(1)
    $rng.GetBytes($buf)
    return $buf[0]
}

function Get-RandomUInt32 {
    $buf = [byte[]]::new(4)
    $rng.GetBytes($buf)
    return [BitConverter]::ToUInt32($buf, 0)
}

# XOR mask for public key (changes every build)
$keyMask = Get-RandomByte
if ($keyMask -eq 0) { $keyMask = 0x5A }

# XOR mask for server string (changes every build)
$strMask = Get-RandomByte
if ($strMask -eq 0) { $strMask = 0x3C }

# Parse public key hex to bytes
$pubKeyBytes = [byte[]]::new(32)
for ($i = 0; $i -lt 32; $i++) {
    $pubKeyBytes[$i] = [Convert]::ToByte($pubKeyHex.Substring($i * 2, 2), 16)
}

# Generate XOR-encoded key array
$encodedKey = ($pubKeyBytes | ForEach-Object { "0x{0:X2}" -f ($_ -bxor $keyMask) }) -join ", "

# Generate XOR-encoded server host (as char array)
$hostBytes = [System.Text.Encoding]::ASCII.GetBytes($host_)
$encodedHost = ($hostBytes | ForEach-Object { "0x{0:X2}" -f ($_ -bxor $strMask) }) -join ", "

# Generate XOR-encoded full URL
$fullUrl = "https://${host_}"
$urlBytes = [System.Text.Encoding]::ASCII.GetBytes($fullUrl)
$encodedUrl = ($urlBytes | ForEach-Object { "0x{0:X2}" -f ($_ -bxor $strMask) }) -join ", "

# Wide-char host for WinHTTP (UTF-16LE XOR'd with 16-bit mask)
$wstrMask = Get-RandomUInt32 -band 0xFFFF
if ($wstrMask -eq 0) { $wstrMask = 0x4B2E }
$wideHost = ($hostBytes | ForEach-Object { "0x{0:X4}" -f ($_ -bxor $wstrMask) }) -join ", "

# Canary value (random, embedded in binary, checked at runtime to detect patching)
$canary = Get-RandomUInt32

# Pre-compute hex strings for use in here-strings
$keyMaskHex = "{0:X2}" -f [int]$keyMask
$strMaskHex = "{0:X2}" -f [int]$strMask
$wstrMaskHex = "{0:X4}" -f ($wstrMask % 65536)
$canaryHex = $canary.ToString("X8")
# ============================================================================
# Output: generated/server_config.h
# ============================================================================
$outDir = "$PSScriptRoot\generated"
if (!(Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }

$serverConfigH = @"
#pragma once
// ============================================================================
// AUTO-GENERATED by generate_config.ps1 — DO NOT EDIT
// All values are compile-time obfuscated. Masks change every build.
// ============================================================================
#include <cstdint>
#include <string>

namespace cobble_config {

// Build metadata
constexpr const char* VERSION = "$version";
constexpr uint32_t BUILD_CANARY = 0x${canaryHex}u;

// Server (XOR-encoded, decoded at runtime)
namespace _internal {
    constexpr uint8_t STR_MASK = 0x$strMaskHex;
    constexpr uint8_t HOST_ENC[] = { $encodedHost };
    constexpr size_t  HOST_LEN = $($hostBytes.Length);
    constexpr uint8_t URL_ENC[] = { $encodedUrl };
    constexpr size_t  URL_LEN = $($urlBytes.Length);
    constexpr uint16_t WSTR_MASK = 0x$wstrMaskHex;
    constexpr uint16_t WHOST_ENC[] = { $wideHost };
}

constexpr int SERVER_PORT = $port;
constexpr bool SERVER_HTTPS = $(if($https){"true"}else{"false"});

// Decode server host at runtime (stack-only, no heap allocation for short strings)
inline std::string GetServerHost() {
    char buf[_internal::HOST_LEN + 1];
    for (size_t i = 0; i < _internal::HOST_LEN; i++)
        buf[i] = (char)(_internal::HOST_ENC[i] ^ _internal::STR_MASK);
    buf[_internal::HOST_LEN] = 0;
    return std::string(buf, _internal::HOST_LEN);
}

inline std::string GetServerUrl() {
    char buf[_internal::URL_LEN + 1];
    for (size_t i = 0; i < _internal::URL_LEN; i++)
        buf[i] = (char)(_internal::URL_ENC[i] ^ _internal::STR_MASK);
    buf[_internal::URL_LEN] = 0;
    return std::string(buf, _internal::URL_LEN);
}

inline std::wstring GetServerHostW() {
    wchar_t buf[_internal::HOST_LEN + 1];
    for (size_t i = 0; i < _internal::HOST_LEN; i++)
        buf[i] = (wchar_t)(_internal::WHOST_ENC[i] ^ _internal::WSTR_MASK);
    buf[_internal::HOST_LEN] = 0;
    return std::wstring(buf, _internal::HOST_LEN);
}

} // namespace cobble_config
"@

$serverConfigH | Out-File "$outDir\server_config.h" -Encoding ASCII

# ============================================================================
# Output: generated/keys.h
# ============================================================================
$keysH = @"
#pragma once
// ============================================================================
// AUTO-GENERATED by generate_config.ps1 — DO NOT EDIT
// Ed25519 public key, XOR-obfuscated with per-build random mask.
// ============================================================================
#include <cstdint>

namespace cobble_keys {

namespace _internal {
    constexpr uint8_t KEY_MASK = 0x$keyMaskHex;
    constexpr uint8_t ENCODED_KEY[32] = { $encodedKey };
}

// Decode public key into caller-provided buffer. Clear after use.
inline void GetPublicKey(uint8_t out[32]) {
    for (int i = 0; i < 32; i++)
        out[i] = _internal::ENCODED_KEY[i] ^ _internal::KEY_MASK;
}

} // namespace cobble_keys
"@

$keysH | Out-File "$outDir\keys.h" -Encoding ASCII

# ============================================================================
# Output: generated/payload_key.h (loader only — not included by DLL)
# ============================================================================
# The payload key is XOR'd with a random 32-byte pad. Decoded at runtime.
$pkBytes = [byte[]]::new(32)
for ($i = 0; $i -lt 32; $i++) {
    $pkBytes[$i] = [Convert]::ToByte($payloadKey.Substring($i * 2, 2), 16)
}
$pkPad = [byte[]]::new(32)
$rng.GetBytes($pkPad)
$pkEncoded = [byte[]]::new(32)
for ($i = 0; $i -lt 32; $i++) { $pkEncoded[$i] = $pkBytes[$i] -bxor $pkPad[$i] }

$pkEncodedStr = ($pkEncoded | ForEach-Object { "0x{0:X2}" -f $_ }) -join ", "
$pkPadStr = ($pkPad | ForEach-Object { "0x{0:X2}" -f $_ }) -join ", "

$payloadKeyH = @"
#pragma once
// ============================================================================
// AUTO-GENERATED — Payload AES key, XOR-encrypted with per-build random pad.
// Only included by the loader. The DLL never sees this.
// ============================================================================
#include <cstdint>
#include <string>

namespace cobble_payload {

namespace _internal {
    constexpr uint8_t KEY_ENC[32] = { $pkEncodedStr };
    constexpr uint8_t KEY_PAD[32] = { $pkPadStr };
}

// Returns the 64-char hex payload key. Call once, use, then zero the string.
inline std::string GetPayloadKeyHex() {
    char hex[65];
    const char* hexchars = "0123456789abcdef";
    for (int i = 0; i < 32; i++) {
        uint8_t b = _internal::KEY_ENC[i] ^ _internal::KEY_PAD[i];
        hex[i*2]   = hexchars[b >> 4];
        hex[i*2+1] = hexchars[b & 0x0F];
    }
    hex[64] = 0;
    return std::string(hex, 64);
}

} // namespace cobble_payload
"@

$payloadKeyH | Out-File "$outDir\payload_key.h" -Encoding ASCII

Write-Host "  [CONFIG] Generated headers with mask=0x$keyMaskHex, str_mask=0x$strMaskHex, canary=0x$canaryHex"
